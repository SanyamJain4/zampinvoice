"""Integration: every generated PDF goes through the SAME pipeline as a user upload (upload -> process -> decision).

Expected outcomes come from sample_data/test_manifest.json (written by the generator), never from the filename.
A markdown report of actual vs expected is written to docs/TEST_REPORT.md.
"""
from pathlib import Path

import pytest

from tests.conftest import MANIFEST, ROOT, SAMPLE_DIR, process_path, rule

REPORT: list[dict] = []


def test_manifest_end_to_end(fresh):
    problems = []
    for item in sorted(MANIFEST["invoices"], key=lambda i: i["run_order"]):
        detail = process_path(fresh, SAMPLE_DIR / item["file"])
        exp = item["expected"]
        actual = detail["final_decision"]
        row = {"file": item["file"].split("/")[-1], "title": item["title"], "expected": exp["decision"], "actual": actual,
               "rules": {}, "ok": True, "reason": detail["decision_reason"], "ocr": item["scanned"]}
        if actual != exp["decision"]:
            row["ok"] = False
            problems.append(f"{row['file']}: expected {exp['decision']} got {actual} ({detail['decision_reason']})")
        for rid, st in (exp.get("rules") or {}).items():
            got = rule(detail, rid)["status"] if detail["validations"] else "—"
            row["rules"][rid] = f"{st} (got {got})"
            if got != st:
                row["ok"] = False
                problems.append(f"{row['file']}: {rid} expected {st} got {got}")
        if exp.get("remaining_after"):
            ra = detail["decision"]["allocation"]["remaining_after"]
            if ra != exp["remaining_after"]:
                row["ok"] = False
                problems.append(f"{row['file']}: remaining_after expected {exp['remaining_after']} got {ra}")
        if item["scanned"]:
            assert detail["extraction_method"] and detail["ocr_confidence"] is not None, "scanned PDF must go through OCR"
        REPORT.append(row)
    _write_report()
    assert not problems, "\n".join(problems)


def _write_report():
    lines = ["# Test report: manifest pipeline run", "", f"_Generated by `pytest backend/tests/test_manifest_pipeline.py` (data generated on {MANIFEST['generated_on']})._", "",
             "| # | Input file | Scenario | Expected | Actual | Rule checks | Result |", "|---|---|---|---|---|---|---|"]
    for i, r in enumerate(REPORT, 1):
        rules = "<br>".join(f"{k}: {v}" for k, v in r["rules"].items()) or "—"
        lines.append(f"| {i} | `{r['file']}` | {r['title']}{' (OCR)' if r['ocr'] else ''} | {r['expected']} | {r['actual']} | {rules} | {'PASS' if r['ok'] else 'FAIL'} |")
    out = ROOT / "docs" / "TEST_REPORT.md"
    out.parent.mkdir(exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
